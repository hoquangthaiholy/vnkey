import CryptoKit
import Foundation

// Lịch sử clipboard: phần thuần (không chạm NSPasteboard, cửa sổ hay đĩa) để kiểm thử tự động được.

public enum ClipKind: String, Codable, Sendable {
    case text, link, image, file

    /// Một dòng không khoảng trắng, có giao thức http(s) và tên miền thì là đường dẫn; còn lại là văn bản.
    public static func classify(_ text: String) -> ClipKind {
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.isEmpty, !t.contains(where: \.isWhitespace), let u = URLComponents(string: t),
            let scheme = u.scheme?.lowercased(), scheme == "http" || scheme == "https", !(u.host ?? "").isEmpty
        else { return .text }
        return .link
    }
}

public struct ClipItem: Codable, Equatable, Sendable {
    /// Mã băm của nội dung: cùng nội dung thì cùng `id` trên mọi máy, nên sao chép lại hay đồng bộ không sinh bản trùng.
    public var id: String
    public var kind: ClipKind
    /// Văn bản; địa chỉ; các đường dẫn tệp (mỗi dòng một tệp); rỗng với ảnh (ảnh nằm ở tệp `<id>.png`).
    public var text: String
    /// Lần sao chép gần nhất: thứ tự hiển thị.
    public var date: Date
    /// Lần đổi gần nhất (sao chép lại, ghim): bản mới hơn thắng khi đồng bộ.
    public var modified: Date
    /// Ứng dụng nguồn (bundle ID).
    public var app: String?
    public var pinned = false
    /// Tên máy đã sao chép; nil = máy này.
    public var device: String?
    /// Có bản mang định dạng kèm theo (`<id>.rtfd`, `<id>.rtf`, `<id>.html`) để dán giữ định dạng.
    public var rich = false
    public var width: Int?
    public var height: Int?

    public init(kind: ClipKind, text: String, date: Date, app: String? = nil, imageData: Data? = nil) {
        self.id = ClipItem.makeID(kind: kind, text: text, imageData: imageData)
        self.kind = kind; self.text = text; self.date = date; self.modified = date; self.app = app
    }

    public static func makeID(kind: ClipKind, text: String, imageData: Data? = nil) -> String {
        var h = SHA256()
        h.update(data: Data((kind == .link ? ClipKind.text : kind).rawValue.utf8))
        h.update(data: imageData ?? Data(text.utf8))
        return h.finalize().prefix(16).map { String(format: "%02x", $0) }.joined()
    }

    /// Một dòng để hiện trong danh sách.
    public var title: String {
        switch kind {
        case .image: return ""
        case .file:
            return text.split(separator: "\n").map { ($0 as NSString).lastPathComponent }.joined(separator: ", ")
        case .text, .link:
            return text.prefix(400).split(whereSeparator: \.isWhitespace).joined(separator: " ")
        }
    }

    /// Tên miền của đường dẫn, bỏ "www.".
    public var host: String? {
        guard kind == .link, let h = URLComponents(string: text.trimmingCharacters(in: .whitespacesAndNewlines))?.host else { return nil }
        return h.hasPrefix("www.") ? String(h.dropFirst(4)) : h
    }

    public var paths: [String] { kind == .file ? text.split(separator: "\n").map(String.init) : [] }
}

/// Có nên ghi một lần sao chép vào lịch sử không.
public enum ClipPolicy {
    /// Quy ước nspasteboard.org: trình quản lý mật khẩu và các app tự sinh nội dung đánh dấu bằng các kiểu này.
    public static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]
    /// Kiểu VNKey tự gắn khi nó ghi lên pasteboard để dán: không ghi lại chính mình.
    public static let ownType = "local.vnkey.clipboard"

    public static func shouldCapture(types: [String], app: String?, excluded: Set<String>, secureInput: Bool) -> Bool {
        if secureInput { return false }
        if let app, excluded.contains(app) { return false }
        return !types.contains { skippedTypes.contains($0) || $0 == ownType }
    }
}

public enum ClipSearch {
    /// Chữ thường, bỏ dấu: gõ "viet" tìm ra "Việt".
    public static func fold(_ s: String) -> String {
        s.replacingOccurrences(of: "đ", with: "d").replacingOccurrences(of: "Đ", with: "D")
            .folding(options: [.diacriticInsensitive, .caseInsensitive], locale: nil)
    }

    /// Mọi từ trong câu tìm đều phải có mặt (không cần liền nhau).
    public static func matches(_ item: ClipItem, _ query: String, extra: String = "") -> Bool {
        let words = fold(query).split(whereSeparator: \.isWhitespace)
        if words.isEmpty { return true }
        let hay = fold(item.text + " " + extra)
        return words.allSatisfy { hay.contains($0) }
    }
}

/// Danh sách các mục đã sao chép, mới nhất trước. Mục ghim không bị đẩy ra khi đầy.
public struct ClipHistory {
    public private(set) var items: [ClipItem] = []
    public var limit: Int
    public private(set) var dirty = false
    /// Mục vừa rời lịch sử: app xoá tệp ảnh / RTF đi kèm rồi gọi `takeRemoved`.
    private var removed: [String] = []

    public init(limit: Int = 200) { self.limit = limit }

    public func item(_ id: String) -> ClipItem? { items.first { $0.id == id } }

    /// Thêm một lần sao chép. Nội dung đã có thì chỉ đưa lên đầu (giữ trạng thái ghim).
    public mutating func add(_ new: ClipItem) {
        var item = new
        if let i = items.firstIndex(where: { $0.id == new.id }) {
            item.pinned = items[i].pinned
            items.remove(at: i)
        }
        items.insert(item, at: 0)
        settle()
    }

    /// Nhận một mục từ máy khác (hoặc bản mới hơn của mục đang có).
    public mutating func adopt(_ remote: ClipItem) {
        items.removeAll { $0.id == remote.id }
        items.append(remote)
        settle()
    }

    public mutating func togglePin(_ id: String, now: Date = Date()) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle()
        items[i].modified = now
        settle()
    }

    public mutating func remove(_ id: String) {
        guard items.contains(where: { $0.id == id }) else { return }
        items.removeAll { $0.id == id }
        removed.append(id)
        dirty = true
    }

    public mutating func clear() {
        removed += items.map(\.id)
        items = []
        dirty = true
    }

    public mutating func takeRemoved() -> [String] {
        defer { removed = [] }
        return removed
    }

    public mutating func markSaved() { dirty = false }

    /// Thứ tự hiển thị: mục ghim trước, rồi theo thời gian; lọc theo câu tìm.
    public func visible(_ query: String = "", extra: (ClipItem) -> String = { _ in "" }) -> [ClipItem] {
        let hit = items.filter { ClipSearch.matches($0, query, extra: extra($0)) }
        return hit.filter(\.pinned) + hit.filter { !$0.pinned }
    }

    private mutating func settle() {
        items.sort { $0.date > $1.date }
        var free = 0
        items.removeAll { item in
            if item.pinned { return false }
            free += 1
            if free > limit { removed.append(item.id); return true }
            return false
        }
        dirty = true
    }

    // MARK: Lưu

    private struct Stored: Codable {
        var version = 1
        var items: [ClipItem]
    }

    public func data() -> Data { (try? ClipCoding.encoder.encode(Stored(items: items))) ?? Data() }

    public init?(data: Data, limit: Int = 200) {
        guard let s = try? ClipCoding.decoder.decode(Stored.self, from: data), s.version == 1 else { return nil }
        self.limit = limit
        items = s.items
        settle()
        dirty = false
        removed = []
    }
}

enum ClipCoding {
    static let encoder: JSONEncoder = {
        let e = JSONEncoder()
        e.dateEncodingStrategy = .millisecondsSince1970
        e.outputFormatting = [.sortedKeys]
        return e
    }()
    static let decoder: JSONDecoder = {
        let d = JSONDecoder()
        d.dateDecodingStrategy = .millisecondsSince1970
        return d
    }()
}

/// Đồng bộ lịch sử qua một thư mục dùng chung (iCloud Drive): mỗi mục một tệp `<id>.json`.
/// Ở đây chỉ có luật hoà trộn; việc đọc/ghi tệp do app làm.
public enum ClipSync {
    public static let maxBytes = 100_000

    /// Chỉ văn bản và đường dẫn, không quá 100 KB. Ảnh và tệp ở lại máy đã sao chép.
    public static func syncable(_ item: ClipItem) -> Bool {
        (item.kind == .text || item.kind == .link) && item.text.utf8.count <= maxBytes
    }

    public struct Plan: Equatable {
        /// Ghi (hoặc ghi đè) tệp cho các mục này.
        public var upload: [ClipItem] = []
        /// Đưa các mục này vào lịch sử ở máy.
        public var adopt: [ClipItem] = []
        /// Máy khác đã xoá: xoá ở máy này.
        public var deleteLocal: [String] = []
        /// Máy này đã xoá (hoặc đẩy khỏi lịch sử): xoá tệp.
        public var deleteRemote: [String] = []
        /// Các mục có mặt ở cả hai phía sau khi thi hành; lưu lại cho lần đối chiếu sau.
        public var known: Set<String> = []

        public var isEmpty: Bool { upload.isEmpty && adopt.isEmpty && deleteLocal.isEmpty && deleteRemote.isEmpty }
    }

    /// `known`: các mục lần trước có ở cả hai phía. Mục "đã biết" mà nay thiếu ở một phía nghĩa là phía đó đã xoá;
    /// mục chưa biết mà chỉ có ở một phía là mục mới của phía đó.
    public static func reconcile(local: [ClipItem], remote: [ClipItem], known: Set<String>) -> Plan {
        var plan = Plan()
        // iCloud có thể để lại bản sao xung đột ("… 2.json"): nhận theo `id` bên trong, lấy bản mới nhất.
        var far: [String: ClipItem] = [:]
        for r in remote where syncable(r) {
            if let old = far[r.id], old.modified >= r.modified { continue }
            far[r.id] = r
        }
        var near: Set<String> = []
        for l in local where syncable(l) {
            near.insert(l.id)
            if let r = far[l.id] {
                if r.modified > l.modified { plan.adopt.append(r) } else if l.modified > r.modified { plan.upload.append(l) }
                plan.known.insert(l.id)
            } else if known.contains(l.id) {
                plan.deleteLocal.append(l.id)
            } else {
                plan.upload.append(l)
                plan.known.insert(l.id)
            }
        }
        for (id, r) in far where !near.contains(id) {
            if known.contains(id) {
                plan.deleteRemote.append(id)
            } else {
                plan.adopt.append(r)
                plan.known.insert(id)
            }
        }
        plan.adopt.sort { $0.id < $1.id }
        plan.deleteRemote.sort()
        return plan
    }

    public static func encode(_ item: ClipItem, device: String) -> Data {
        var out = item
        if out.device == nil { out.device = device }
        return (try? ClipCoding.encoder.encode(out)) ?? Data()
    }

    /// Đọc một tệp đồng bộ. Mục do chính máy này ghi thì bỏ tên máy.
    public static func decode(_ data: Data, device: String) -> ClipItem? {
        guard var item = try? ClipCoding.decoder.decode(ClipItem.self, from: data), syncable(item),
            item.id == ClipItem.makeID(kind: item.kind, text: item.text)
        else { return nil }
        if item.device == device { item.device = nil }
        item.rich = false
        return item
    }
}
